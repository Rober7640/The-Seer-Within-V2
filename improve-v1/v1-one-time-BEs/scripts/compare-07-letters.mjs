/**
 * 07 — put the same letter, written by different models from ONE brief, side by side.
 *
 *   node scripts/compare-07-letters.mjs
 *
 * ⭐ Day 9 "He's Gone Quiet" was written three times from
 *    docs/07-marcus/07-brief-day-09-hes-gone-quiet.md — same spread, same named thing, same
 *    opening shape. So any difference in the output is the WRITER, not the brief. That is the
 *    only reason the comparison means anything.
 *
 * ⛔ Regenerate rather than hand-edit the output. A writer that has not filed yet shows as
 *    PENDING instead of being silently left out — a missing letter must never read as a letter
 *    that was written and found wanting.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const D = 'copy/07-marcus/daily';

const ENTRANTS = [
  // ⭐ Written from the REBUILT voice profile alone — no day-9 brief, deliberately, to test
  //    whether that one document transmits the voice to a writer who has never seen the offer.
  { who: 'Claude · new voice profile', model: 'claude-opus-5', via: 'profile only, no brief',
    file: `${D}/compare/07-D3-hes-gone-quiet-voiceprofile.md` },
  { who: 'Claude',           model: 'claude-opus-5',        via: 'Agent tool',
    file: `${D}/compare/07-D3-hes-gone-quiet-claude.md` },
  // ⭐ Same writer, same brief, but written AFTER the voice profile was rebuilt. The pair
  //    below is the only controlled read we have on whether that document changes anything.
  { who: 'GPT · astra + new profile', model: 'gpt-6-astra', via: 'profile + brief',
    file: `${D}/compare/07-D3-hes-gone-quiet-astra-v2.md` },
  { who: 'GPT · astra',      model: 'gpt-6-astra',          via: 'brief only, old profile',
    file: `${D}/compare/07-D3-hes-gone-quiet-astra.md` },
  { who: 'GPT · spark',      model: 'gpt-5.3-codex-spark',  via: 'codex-rescue plugin',
    file: `${D}/07-D3-hes-gone-quiet.md` },
];

const read = (p) => (fs.existsSync(path.join(ROOT, p)) ? fs.readFileSync(path.join(ROOT, p), 'utf8') : null);
const cell = (md, k) => (md.match(new RegExp(`^\\*\\*${k}\\*\\*\\s*[—-]\\s*(.+?)$`, 'm')) || [, ''])[1]
  .trim().replace(/^`|`$/g, '');
const name = (s) => s.replace(/\{\{[^}]*\}\}/g, 'Sarah').replace(/\s+,/g, ',').trim();

/** The letter as she reads it — no metadata table, no builder notes, no beat markers. */
function body(md) {
  let t = md.includes('\n---') ? md.split(/\n---\s*\n/).slice(1).join('\n---\n') : md;
  t = t.replace(/<!--[\s\S]*?-->/g, '')
       .replace(/\{\{\s*subscriber\.first_name\s*\|\s*capitalize\s*\}\}/g, 'Sarah')
       .replace(/\{\{\s*BOOKING_URL\s*\}\}/g, '(booking link)')
       .replace(/\{\{[^}]*\}\}/g, '');
  const keep = t.split(/\n\s*\n/).map((p) => p.trim())
    .filter((p) => p && !/^(⛔|⚠|\||\*\*Subject\*\*|\*\*Preheader\*\*)/.test(p));
  return keep.join('\n\n').replace(/\n{3,}/g, '\n\n').trim();
}
const words = (t) => t.replace(/[#*|`>]/g, ' ').split(/\s+/).filter(Boolean).length;

const rows = ENTRANTS.map((e) => {
  const md = read(e.file);
  if (!md) return { ...e, pending: true };
  const b = body(md);
  return { ...e, md, b, words: words(b),
           subject: name(cell(md, 'Subject')), pre: name(cell(md, 'Preheader')),
           card: (md.match(/`evelyn\/tarot-rws\/([a-z0-9-]+)`/) || [, '—'])[1] };
});

const out = [];
out.push(`# 07 · day 9 "He's Gone Quiet" — the same letter, three writers

⭐ **One brief, three models.** Every writer got
[\`07-brief-day-09-hes-gone-quiet.md\`](./07-brief-day-09-hes-gone-quiet.md) and nothing else —
same spread, same seven \`job\` strings, same named thing, same QUESTION FIRST opening shape,
same list of seven cards it may not reuse. **So a difference below is the writer, not the brief.**

Each writer chose its own card. None read another's answer.

⚠ **One asymmetry, stated so it is not mistaken for a clean experiment.** Claude was additionally
warned about two defects already found in spark's draft (the "you sent it" slip and a duplicated
paragraph opener). GPT·astra and GPT·spark were not. Claude had that advantage.

Generated by \`scripts/compare-07-letters.mjs\` — ⛔ regenerate, do not hand-edit.

---

## At a glance

| | Writer | Model | Route | Words | Card | Filed |
|---|---|---|---|---|---|---|`);

for (const r of rows) {
  out.push(`| ${r.pending ? '⏳' : '✅'} | **${r.who}** | \`${r.model}\` | ${r.via} | ` +
    `${r.pending ? '—' : r.words.toLocaleString()} | ${r.pending ? '—' : r.card} | ` +
    `${r.pending ? '**PENDING**' : 'yes'} |`);
}

out.push(`
**The length standard, set by the operator 2026-09-06: ~1,000 words, copy-check warns over 1,200.**
⛔ The earlier 1,769–2,086 band was never a standard — it is just what the first six happened to
come out at, and it hardened into one by accident. Three of the four below are over the real cap.

## Subject lines, side by side
`);
for (const r of rows) {
  out.push(r.pending ? `**${r.who}** — ⏳ pending\n`
                     : `**${r.who}**\n> ${r.subject}\n`);
}

out.push(`---\n`);

for (const r of rows) {
  out.push(`## ${r.who} — \`${r.model}\`\n`);
  if (r.pending) {
    out.push(`⏳ **Not filed yet.** Expected at \`${r.file}\`. Re-run the generator when it lands.\n\n---\n`);
    continue;
  }
  out.push(`| | |
|---|---|
| **Route** | ${r.via} |
| **Card** | \`${r.card}\` |
| **Words** | ${r.words.toLocaleString()} |
| **Source** | \`${r.file}\` |

**Subject** — ${r.subject}

**Preheader** — ${r.pre}

${r.b}

---
`);
}

const dest = 'docs/07-marcus/07-day-09-three-ways.md';
fs.writeFileSync(path.join(ROOT, dest), out.join('\n') + '\n');
const done = rows.filter((r) => !r.pending).length;
console.log(`wrote ${dest} — ${done}/${rows.length} letters` +
  (done < rows.length ? `  ⏳ ${rows.filter((r) => r.pending).map((r) => r.who).join(', ')} still pending` : ''));
