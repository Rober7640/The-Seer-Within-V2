/**
 * 07 — the two three-card formats, every draft side by side.
 *
 *   node scripts/compare-07-formats.mjs
 *
 * ⭐ Each pair is ONE brief, ONE voice profile, two writers. The only variable is the model, so a
 *    difference below is the writer. Nobody read anybody else's draft — verified per run.
 * ⛔ Regenerate; do not hand-edit. A writer that has not filed shows as PENDING rather than being
 *    quietly left out — a missing letter must never read as one that was written and found wanting.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { spread } from './07-registry.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const C = 'copy/07-marcus/daily/compare';

const FORMATS = [
  { key: 'past-present-future',   brief: 'docs/07-marcus/07-brief-past-present-future.md' },
  { key: 'problem-action-outcome', brief: 'docs/07-marcus/07-brief-problem-action-outcome.md' },
];
const WRITERS = [
  { who: 'Claude',      model: 'claude-opus-5', suffix: 'claude' },
  { who: 'GPT · astra', model: 'gpt-6-astra',   suffix: 'astra' },
];

const read = (p) => (fs.existsSync(path.join(ROOT, p)) ? fs.readFileSync(path.join(ROOT, p), 'utf8') : null);
const cell = (md, k) => (md.match(new RegExp(`^\\*\\*${k}\\*\\*\\s*[—-]\\s*(.+?)$`, 'm')) || [, ''])[1].trim().replace(/^`|`$/g, '');
const nm = (s) => s.replace(/\{\{[^}]*\}\}/g, 'Sarah').replace(/\s+,/g, ',').trim();

function body(md) {
  let t = md.includes('\n---') ? md.split(/\n---\s*\n/).slice(1).join('\n---\n') : md;
  t = t.replace(/<!--[\s\S]*?-->/g, '')
       .replace(/\{\{\s*subscriber\.first_name\s*\|\s*capitalize\s*\}\}/g, 'Sarah')
       .replace(/\{\{\s*BOOKING_URL\s*\}\}/g, '(booking link)')
       .replace(/\{\{[^}]*\}\}/g, '');
  return t.split(/\n\s*\n/).map((p) => p.trim())
    .filter((p) => p && !/^(⛔|⚠|\||\*\*Subject\*\*|\*\*Preheader\*\*)/.test(p))
    .join('\n\n').replace(/\n{3,}/g, '\n\n').trim();
}
const wc = (t) => t.replace(/[#*|`>]/g, ' ').split(/\s+/).filter(Boolean).length;
const bare = (t) => (t.match(/(?:^|\n\n)\s*(Which|That|This|It|Those|These|There)\b/g) || []).length;

const out = [`# 07 · the two three-card formats — every draft, side by side

⭐ **The format is generic on purpose; the reading is not.** The position names are the plainest in
tarot, so nothing has to be explained before the reading starts. All the specificity lives in the
\`job\` strings, and those go verbatim into the model prompt.

⭐ **Why a plain format is allowed to be the product.** Nobody shops for a named spread — card
structure appears three times in ~130 Etsy listings and never as the product. But **an inbox is not
a shop**: on a listing she has ten words and two seconds, in an email Marcus has a thousand words to
set the frame before he asks for anything.

Each pair below is one brief, one voice profile, two writers. Nobody read anybody else's draft.

Generated by \`scripts/compare-07-formats.mjs\` — ⛔ regenerate, do not hand-edit.

---
`];

for (const f of FORMATS) {
  const sp = spread(f.key);
  const free = sp.positions.filter((p) => p.free);
  const paid = sp.positions.filter((p) => !p.free);
  out.push(`## ${sp.name}

**Her question:** *${sp.question}*
**Brief:** \`${f.brief}\` · **Registry key:** \`${f.key}\` · **${free.length} free + ${paid.length} paid**, ladder 6 / 9 / 12

| # | | Position | \`job\` — what it must FIND |
|---|---|---|---|`);
  for (const p of sp.positions) {
    out.push(`| ${p.n} | ${p.free ? '**FREE**' : 'paid'} | **${p.name}** | ${p.job} |`);
  }

  const rows = WRITERS.map((w) => {
    const file = `${C}/07-D3-${f.key}-${w.suffix}.md`;
    const md = read(file);
    if (!md) return { ...w, file, pending: true };
    const b = body(md);
    return { ...w, file, md, b, words: wc(b), bare: bare(b),
             subject: nm(cell(md, 'Subject')), pre: nm(cell(md, 'Preheader')),
             card: (md.match(/`evelyn\/tarot-rws\/([a-z0-9-]+)`/) || [, '—'])[1] };
  });

  out.push(`\n### The drafts\n
| Writer | Model | Words | Card | Bare demonstratives | Filed |
|---|---|---|---|---|---|`);
  for (const r of rows) {
    out.push(`| **${r.who}** | \`${r.model}\` | ${r.pending ? '—' : r.words.toLocaleString()} | ` +
      `${r.pending ? '—' : r.card} | ${r.pending ? '—' : r.bare} | ${r.pending ? '⏳ **PENDING**' : '✅'} |`);
  }
  const cards = rows.filter((r) => !r.pending).map((r) => r.card);
  if (cards.length === 2 && cards[0] === cards[1]) {
    out.push(`\n⭐ **Both writers independently chose \`${cards[0]}\`.** Neither read the other's draft.
That is evidence the \`job\` string is specific enough to point at one card — which is the whole bet
of this format: plain labels, sharp jobs.`);
  }
  out.push('');

  for (const r of rows) {
    out.push(`### ${sp.name} — ${r.who}\n`);
    if (r.pending) { out.push(`⏳ **Not filed yet.** Expected at \`${r.file}\`. Re-run the generator.\n\n---\n`); continue; }
    out.push(`\`${r.file}\` · **${r.words.toLocaleString()} words** · card \`${r.card}\`

**Subject** — ${r.subject}

**Preheader** — ${r.pre}

${r.b}

---
`);
  }
}

const dest = 'docs/07-marcus/07-three-card-formats.md';
fs.writeFileSync(path.join(ROOT, dest), out.join('\n') + '\n');
const done = out.join('').match(/⏳/g);
console.log(`wrote ${dest}${done ? `  ⏳ ${done.length} still pending` : '  — all filed'}`);
