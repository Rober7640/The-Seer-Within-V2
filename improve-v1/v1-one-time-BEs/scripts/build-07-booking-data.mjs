/**
 * 07 — regenerate the booking page's registry island, and ASSERT it.
 *
 *   node scripts/build-07-booking-data.mjs          # rewrite the island in place
 *   node scripts/build-07-booking-data.mjs --check  # fail if it is stale, write nothing
 *
 * ⭐ WHY THIS EXISTS. `copy/07-marcus/07-C1-booking-page.html` is a standalone file the
 *    operator opens off disk, so it cannot import 07-registry.mjs at run time. It carries a
 *    GENERATED copy of the numbers instead, between /*BEGIN-REGISTRY* / markers, and this
 *    script is the only thing allowed to write them.
 *
 * ⭐ IT COVERS EVERY PAGE, NOT ONE. Any `copy/07-marcus/07-C1-booking-page*.html` that carries
 *    the markers is written and checked — the locked reference page and the five candidate
 *    designs alike. A candidate is a page that can take money, so it gets the same guard as the
 *    reference; a design the operator has not picked yet is exactly when a number drifts.
 *    ⛔ A file matching the glob with NO markers is left alone (07-C1-booking-page-preview.html
 *    is the dead 07-C2 mockup and has none), but a file with only ONE marker is a failure.
 *
 * ⛔ The one failure this offer cannot survive is the number she is SOLD and the number
 *    fulfilment DELIVERS being computed by two pieces of code that can disagree. So every
 *    count in the island comes from `resolve()` and is checked against `tierTable()` before
 *    the file is written. Hand-editing the island is the bug this guards.
 *
 * ⛔ Copy is NOT generated. Everything Marcus says lives in the `COPY` object in the HTML and
 *    is the operator's to edit. This writes numbers, names, positions and asset keys only.
 */
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { REGISTRY, TIER_MODEL, ORDER, spreads, resolve, cardCounts, tierTable } from './07-registry.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DIR = path.join(HERE, '..', 'copy', '07-marcus');
const BEGIN = '/*BEGIN-REGISTRY*/';
const END = '/*END-REGISTRY*/';

/** Every candidate booking page that carries an island — the reference plus -v1…-v5. */
function pages() {
  const hits = fs.readdirSync(DIR)
    .filter((f) => /^07-C1-booking-page.*\.html$/.test(f))
    .sort()
    .map((f) => ({ file: f, full: path.join(DIR, f), html: fs.readFileSync(path.join(DIR, f), 'utf8') }));
  const carrying = [];
  for (const p of hits) {
    const a = p.html.indexOf(BEGIN), b = p.html.indexOf(END);
    if (a < 0 && b < 0) continue;                       // no island — not a generated page
    if (a < 0 || b < 0 || b < a) {
      console.error(`⛔ ${p.file}: one marker without the other. An island needs both.`);
      process.exit(1);
    }
    carrying.push({ ...p, a, b });
  }
  return carrying;
}

const DAY_NAME = { mon: 'Monday', tue: 'Tuesday', wed: 'Wednesday', thu: 'Thursday',
  fri: 'Friday', sat: 'Saturday', sun: 'Sunday' };

// ── build ─────────────────────────────────────────────────────────────────────
const out = {
  _: 'GENERATED by scripts/build-07-booking-data.mjs from scripts/07-spreads.json. Do not hand-edit.',
  generated_at: new Date().toISOString().slice(0, 10),
  tier_model: {
    id: TIER_MODEL.id,
    order: ORDER,
    open_per_question: TIER_MODEL.open_per_question,
    open_draw_size: TIER_MODEL.open_draw_size,
    closing_passage_tier: TIER_MODEL.closing_passage_tier,
    tiers: Object.fromEntries(ORDER.map((t) => [t, {
      label: TIER_MODEL.tiers[t].label,
      questions: TIER_MODEL.tiers[t].questions,
      price_usd: TIER_MODEL.tiers[t].price_usd,
    }])),
  },
  // ⚠ NOT in 07-spreads.json — 07-C1 beat 10 / open thread 2 is the source. If the bump ever
  //    moves, it moves here and in priceBackendOffer, and nowhere else.
  bump: { product_key: 'marcus_same_day', label: 'Back before tonight', price_usd: 12.77 },
  spreads: {},
};

const problems = [];
/**
 * ⭐ Spreads DESIGNED but not yet shot. The 30-day test writes a registry entry in Phase 2 and
 * the morning's cards in Phase 3, so between those a spread has positions and no `built_email`.
 * It cannot go on the booking page — that page names the cards she saw this morning, and there
 * are none — so it is left out of the island and REPORTED. ⛔ Never silently: a spread missing
 * from the island is a `&s=` link that renders the "unknown spread" list instead of an offer.
 */
const notShot = [];

for (const [key, s] of spreads()) {
  if (!s.built_email) { notShot.push(key); continue; }
  const counts = cardCounts(key);
  for (const t of ORDER) {
    const r = resolve(key, t);
    if (!r.ok) problems.push(`${key}/${t}: ${r.reason}`);
  }
  const built = s.built_email || {};
  const faceUp = new Map((built.face_up || []).map((f) => [f.n, f]));

  const freeRaw = s.positions.filter((p) => p.free);
  const paidRaw = s.positions.filter((p) => !p.free);

  // every free position must have a card, or the "you saw X this morning" line is a lie
  for (const p of freeRaw) {
    if (!faceUp.has(p.n)) problems.push(`${key}: free position ${p.n} has no face_up card`);
  }

  out.spreads[key] = {
    day: s.day,
    day_name: DAY_NAME[s.day],
    name: s.name,
    question: s.question,
    hero: built.hero_asset,
    down: built.facedown_asset,
    cover: built.cover_asset,
    free: freeRaw.map((p) => ({
      n: p.n, name: p.name,
      card: faceUp.get(p.n) ? faceUp.get(p.n).card : null,
      slug: faceUp.get(p.n) ? faceUp.get(p.n).slug : null,
    })),
    paid: paidRaw.map((p) => ({ n: p.n, name: p.name })),
    counts: {
      free: freeRaw.length,
      paid: paidRaw.length,
      spread: counts.spread,
      pattern: counts.pattern,
      table: counts.table,
    },
  };
}

// ── assert against tierTable(), the one arithmetic ────────────────────────────
for (const row of tierTable()) {
  // ⛔ A spread with no cards yet was left out of the island above — it has no counts to
  //    assert against. Reading `.counts` off `undefined` here threw and took the whole
  //    generator down with an unreadable stack, which the checker then reported as
  //    "failed with no diagnosis".
  if (!out.spreads[row.key]) continue;
  const c = out.spreads[row.key].counts;
  for (const t of ORDER) {
    if (c[t] !== row[t]) problems.push(`${row.key}/${t}: island ${c[t]} vs tierTable ${row[t]}`);
  }
  if (c.free + c.paid !== row.spread) {
    problems.push(`${row.key}: free+paid ${c.free + c.paid} != spread total ${row.spread}`);
  }
  // every rung must be live — 07-C5 killed the two ⛔ cells
  if (ORDER.some((t) => row[t] == null)) problems.push(`${row.key}: a rung is missing`);
}
// the increment is constant on all seven days, which is the model's whole legibility claim
for (const row of tierTable()) {
  if (row.pattern - row.spread !== TIER_MODEL.open_per_question ||
      row.table - row.pattern !== TIER_MODEL.open_per_question) {
    problems.push(`${row.key}: increment is not ${TIER_MODEL.open_per_question} per question`);
  }
}

if (problems.length) {
  console.error('⛔ registry problems:\n  ' + problems.join('\n  '));
  process.exit(1);
}

// ── write ─────────────────────────────────────────────────────────────────────
const island = JSON.stringify(out, null, 1);
const check = process.argv.includes('--check');
const targets = pages();

if (!targets.length) {
  console.error(`⛔ no page in ${path.relative(process.cwd(), DIR)} carries the registry markers`);
  process.exit(1);
}

const stale = [];
for (const p of targets) {
  const next = p.html.slice(0, p.a + BEGIN.length) + '\n' + island + '\n' + p.html.slice(p.b);
  if (next === p.html) {
    console.log(`✅ ${p.file} — island is current`);
  } else if (check) {
    stale.push(p.file);
  } else {
    fs.writeFileSync(p.full, next);
    console.log(`✅ ${p.file} — wrote ${island.length} bytes of registry`);
  }
}
if (stale.length) {
  console.error(`⛔ island is STALE in ${stale.length} file(s): ${stale.join(', ')}\n` +
    '   run: node scripts/build-07-booking-data.mjs');
  process.exit(1);
}
console.log(`   ${targets.length} page(s) carry the island`);
if (notShot.length) {
  console.log(`\n⚠ ${notShot.length} spread(s) are NOT on the booking page — designed, no cards yet:`);
  console.log(`   ${notShot.join(' · ')}`);
  console.log('   Their &s= links will not resolve until Phase 3 shoots them.');
}

console.table(tierTable());
console.log(`floor ${REGISTRY.floor} · ${ORDER.map((t) =>
  `${TIER_MODEL.tiers[t].label} $${TIER_MODEL.tiers[t].price_usd}`).join(' · ')} · bump $${out.bump.price_usd}`);
