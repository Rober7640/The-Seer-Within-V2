// build-read-copy — approved drafts -> shared/readCopy.ts
//
// The readings are written as JSON drafts (fb-read/docs/drafts/<device>-<hook>.json)
// and reviewed there, then compiled into the module the app imports. Keeping the
// two apart means copy can be regenerated without anyone editing code, and the
// review gate has a single artifact to sign off.
//
// Refuses to emit anything that is not a complete, reviewed read: exactly seven
// bubbles, none of them the UNWRITTEN sentinel, none over 25 words or 2 sentences.
// A draft that fails is a build failure, not a warning — placeholder copy reaching
// a lander is the one outcome this file exists to prevent.

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'
import { execFileSync } from 'node:child_process'
import { join } from 'node:path'

const DRAFTS = 'fb-read/docs/drafts'
const OUT = 'shared/readCopy.ts'

const files = readdirSync(DRAFTS).filter((f) => f.endsWith('.json')).sort()
if (!files.length) {
  console.error(`no drafts in ${DRAFTS}`)
  process.exit(1)
}

const tree = {}
let failed = 0

for (const file of files) {
  const d = JSON.parse(readFileSync(join(DRAFTS, file), 'utf8'))
  const { device, hook, reads } = d
  if (!device || !hook || !reads) {
    console.error(`${file}: missing device / hook / reads`)
    failed++
    continue
  }

  for (const opt of ['a', 'b', 'c']) {
    const bubbles = reads[opt]
    const where = `${device}/${hook}/${opt}`
    if (!Array.isArray(bubbles) || bubbles.length !== 7) {
      console.error(`${where}: expected 7 bubbles, got ${bubbles?.length ?? 0}`)
      failed++
      continue
    }
    bubbles.forEach((b, i) => {
      const words = b.trim().split(/\s+/).length
      const sentences = b.split(/[.!?…]+/).filter((s) => s.trim()).length
      if (b.includes('__UNWRITTEN__')) { console.error(`${where} cut ${i + 1}: still the sentinel`); failed++ }
      if (words > 25) { console.error(`${where} cut ${i + 1}: ${words} words (max 25)`); failed++ }
      if (sentences > 2) { console.error(`${where} cut ${i + 1}: ${sentences} sentences (max 2)`); failed++ }
      if (b.includes('!')) { console.error(`${where} cut ${i + 1}: exclamation mark`); failed++ }
    })
  }

  tree[device] ??= {}
  tree[device][hook] = { a: reads.a, b: reads.b, c: reads.c }
  console.log(`${file.padEnd(28)} -> ${device}/${hook}  (21 bubbles)`)
}

if (failed) {
  console.error(`\n${failed} problem(s). Nothing written.`)
  process.exit(1)
}

const esc = (s) => JSON.stringify(s)
const body = Object.entries(tree).map(([device, hooks]) => {
  const inner = Object.entries(hooks).map(([hook, opts]) => {
    const rows = ['a', 'b', 'c'].map(
      (o) => `      ${o}: [\n${opts[o].map((b) => `        ${esc(b)},`).join('\n')}\n      ],`,
    ).join('\n')
    return `    ${esc(hook)}: {\n${rows}\n    },`
  }).join('\n')
  return `  ${device}: {\n${inner}\n  },`
}).join('\n')

writeFileSync(OUT, `// GENERATED by scripts/build-read-copy.mjs from ${DRAFTS}/ — do not hand-edit.
// Edit the draft and re-run, or the next regeneration silently reverts you.
//
// SHAPE: seven bubbles per read, written to the Natural Tarot-Cut
// (fb-tarot/docs/natural-tarot-cut.md). Bubble 1 is the picture — on Version C it
// is the ONLY written bubble she sees before she types, so it carries the whole
// first impression, and buildReadReflectPrompt passes it to the model verbatim so
// the reply never re-describes what she has just read.

import type { ReadDevice, ReadHook, ReadOption } from "./readDevices";

export const UNWRITTEN = "__UNWRITTEN__";

export const READS: Partial<
  Record<ReadDevice, Partial<Record<ReadHook, Record<ReadOption, string[]>>>>
> = {
${body}
};

// A read is servable only when it is complete and past the review gate. The
// bridge and the chat route both check this, so a URL handed out early cannot
// serve half-written copy.
export function isReadWritten(
  device: ReadDevice,
  hook: ReadHook,
  option: ReadOption,
): boolean {
  const bubbles = READS[device]?.[hook]?.[option];
  return Array.isArray(bubbles) && bubbles.length === 7 && !bubbles.includes(UNWRITTEN);
}
`)
console.log(`\n-> ${OUT}`)

// 🔴 CLOSE THE LOOP. The registry is generated FROM this file's output, so the
// moment copy changes it is stale. Regenerating here means the normal way copy
// reaches the app also refreshes the registry — there is no separate step anyone
// can forget. tests/fb-read.test.ts then re-checks it, for the paths that do not
// come through here (a new device, a changed guard).
try {
  execFileSync('npx', ['tsx', 'scripts/read-registry.mjs'], { stdio: 'inherit' })
} catch {
  console.error('\nregistry regeneration failed — run: npx tsx scripts/read-registry.mjs')
  process.exit(1)
}
