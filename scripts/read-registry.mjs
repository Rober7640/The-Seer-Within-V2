// read-registry — generate fb-read/docs/lander-registry.md from the code.
//
//   npx tsx scripts/read-registry.mjs            regenerate
//   npx tsx scripts/read-registry.mjs --check    fail if the file on disk is stale
//
// 🔴 THE LOOP. Generating is not enough on its own — a generator nobody runs is a
// stale file with extra steps. Two things close it:
//   1. scripts/build-read-copy.mjs calls this at the end, so the normal way copy
//      reaches the app also refreshes the registry. You cannot ship copy without it.
//   2. tests/fb-read.test.ts runs --check, so editing a device, a hook or a guard
//      without regenerating FAILS THE TEST RUN rather than quietly drifting.
//
// 🔴 GENERATED, NEVER HAND-EDITED, and that is the whole point. A hand-kept status
// board drifts from the code the first time someone ships without updating it, and
// then it lies confidently. This reads the registry, the compiled copy and the
// approved drafts, so it cannot say a lander is something the code denies.
//
// Sources, all of them the real ones the app uses:
//   shared/readDevices.ts   devices, panels, marks, headlines, frames, guards
//   shared/readCopy.ts      whether each reading is actually written
//   fb-read/docs/drafts/    method + VOC provenance per family
//   client/public/read/     whether the art exists on disk

import { writeFileSync, readFileSync, readdirSync, existsSync, statSync } from 'node:fs'
import { join } from 'node:path'
import {
  DEVICES,
  HEADLINES,
  READ_HOOKS,
  READ_QUESTION,
  READ_HOOK_CONTEXT,
  READ_FRAME,
} from '../shared/readDevices.ts'
import { READS, isReadWritten } from '../shared/readCopy.ts'

const DRAFTS = 'fb-read/docs/drafts'
const ART = 'client/public/read'
const OUT = 'fb-read/docs/lander-registry.md'

// Draft provenance, keyed device/hook.
const drafts = {}
if (existsSync(DRAFTS)) {
  for (const f of readdirSync(DRAFTS).filter((x) => x.endsWith('.json'))) {
    const d = JSON.parse(readFileSync(join(DRAFTS, f), 'utf8'))
    drafts[`${d.device}/${d.hook}`] = { ...d, file: f }
  }
}

const kb = (p) => (existsSync(p) ? `${Math.round(statSync(p).size / 1024)} KB` : '—')
const devices = Object.keys(DEVICES)

let md = `# /fb-read — lander registry

**GENERATED by \`npx tsx scripts/read-registry.mjs\`. Do not hand-edit.**
Re-run it after adding a hook, a device, or a reading; it reads the live registry,
the compiled copy and the approved drafts, so it cannot drift from what ships.

A **lander** here is one \`hook × device × panel\` — a registry entry, never a new
page or route. \`/fb-read\` renders every device from \`shared/readDevices.ts\`.

## What exists

| | ${devices.map((d) => `\`${d}\``).join(' | ')} |
|---|${devices.map(() => '---').join('|')}|
`

for (const hook of READ_HOOKS) {
  const cells = devices.map((d) => {
    const n = (DEVICES[d].options ?? []).filter((o) => isReadWritten(d, hook, o)).length
    if (n === 0) return '—'
    return n === DEVICES[d].options.length ? `✅ ${n}/3` : `◐ ${n}/3`
  })
  md += `| **${hook}** | ${cells.join(' | ')} |\n`
}

md += `
✅ all three panels written and servable · ◐ partial · — not built

Every lander runs all three versions; the version is a route, not a property of the
lander:

| Route | Version | What she gets |
|---|---|---|
| \`/fb-read\` | A | the reveal renders on the page, then a short greeting in chat |
| \`/fb-read/b\` | B | no page reveal; the whole written read plays as chat bubbles |
| \`/fb-read/c\` | C | the opening bubble + one question, then the model reads her answer |

**Version C is the priority.** Its fallback is the rest of the written read, so the
copy has to exist in full either way.

---

## Hooks

`

for (const hook of READ_HOOKS) {
  const built = devices.filter((d) => DEVICES[d].options.some((o) => isReadWritten(d, hook, o)))
  const sample = built.map((d) => drafts[`${d}/${hook}`]).find(Boolean)
  md += `### \`${hook}\` — "${HEADLINES[hook]}"

| | |
|---|---|
| Mechanism | ${sample?.method ?? '—'} |
| Frame | \`${sample?.frame ?? '—'}\` |
| Devices built | ${built.length ? built.map((d) => `\`${d}\``).join(', ') : '—'} |
| VOC | ${sample?.voc?.verdict ?? '—'}${sample?.voc?.why ? ` — ${sample.voc.why}` : ''} |

**She is asking:** ${READ_HOOK_CONTEXT[hook]}

**Version C asks her:** *"${READ_QUESTION[hook]}"*

**Frame:** ${READ_FRAME[hook].line}.

<details><summary>The guard (what may never be said on this hook)</summary>

${READ_FRAME[hook].guard}

</details>

`
}

md += `---

## Devices

`

for (const id of devices) {
  const cfg = DEVICES[id]
  md += `### \`${id}\` — ${cfg.eyebrow}

| | |
|---|---|
| Instruction | *"${cfg.instruction}"* |
| Strip | \`${cfg.strip.url}\` · ${cfg.strip.width}×${cfg.strip.height} · ${kb(join(ART, cfg.strip.url.replace('/read/', '')))} |
| Reveal strip | ${cfg.revealStrip ? `\`${cfg.revealStrip.url}\` · ${kb(join(ART, cfg.revealStrip.url.replace('/read/', '')))}` : '— none. Nothing on this device is hidden from her'} |

| Panel | Archetype | The mark named in bubble 1 |
|---|---|---|
${cfg.options.map((o) => `| \`${o}\` | *${cfg.reading[o]}* | ${cfg.mark[o]} |`).join('\n')}

`
}

md += `---

## Live URLs

`
for (const hook of READ_HOOKS) {
  for (const d of devices) {
    if (!DEVICES[d].options.some((o) => isReadWritten(d, hook, o))) continue
    md += `\`\`\`\nhttps://www.theseerwithin.com/fb-read/c?hook=${hook}&device=${d}&utm_content=<ad>\n\`\`\`\n`
  }
}

md += `
Pricing is funnel-level — \`35_read\`, $35/$25 — so every device and hook is priced
correctly with no per-lander roster to keep in step.
`

const total = READ_HOOKS.length * devices.length * 3
const done = READ_HOOKS.flatMap((h) =>
  devices.flatMap((d) => DEVICES[d].options.map((o) => isReadWritten(d, h, o))),
).filter(Boolean).length
const tally = `${done}/${total} landers written across ${READ_HOOKS.length} hooks × ${devices.length} devices`

if (process.argv.includes('--check')) {
  const onDisk = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
  // 🔴 COMPARE LINE-ENDING-INSENSITIVELY, or this check is a guaranteed red on
  // Windows. The file is committed with LF, core.autocrlf=true rewrites it to CRLF on
  // checkout, and `md` is always built with LF — so a byte compare reports STALE on a
  // correct file on every Windows machine, and a guard that is always red protects
  // nothing. Proven by converting the file to CRLF and re-running --check.
  //
  // Only the COMPARISON is normalized. The file is still written with LF below, so
  // what lands in git and what CI sees are both unchanged.
  const norm = (t) => t.split('\r\n').join('\n')
  if (norm(onDisk) !== norm(md)) {
    console.error(`${OUT} is STALE.`)
    console.error('Something in the registry, the copy or the drafts changed without it being regenerated.')
    console.error('Fix: npx tsx scripts/read-registry.mjs')
    process.exit(1)
  }
  console.log(`${OUT} is current — ${tally}`)
  process.exit(0)
}

writeFileSync(OUT, md)
console.log(`-> ${OUT}`)
console.log(`   ${tally}`)
